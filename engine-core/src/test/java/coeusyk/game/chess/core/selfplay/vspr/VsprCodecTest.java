    @Test
    void validOrdinaryCpSample_decodesExactSemanticsAndReEncodesToCanonicalBytes()
            throws Exception {
        byte[] canonical = fixtureBytes("valid_01_ordinary_cp_sample.vspr");
        assertSha256(canonical, "aa1f3c2c8db50d7ba38da13563e2155c24062a3a46874c9f2a407cf77661f055");

        VsprFile file = VsprCodec.read(new ByteArrayInputStream(canonical));
        assertCommonHeader(file.header());
        assertFalse(file.header().candidatesPersisted());

        assertEquals(1, file.frames().size());
        GameFrame frame = file.frames().get(0);
        assertEquals(1L, frame.gameId());
        assertTrue(frame.gameSeed().isEmpty());
        assertEquals(GameOutcome.BLACK_WIN, frame.gameOutcome());
        assertEquals(TerminationReason.CHECKMATE, frame.terminationReason());
        assertEquals(OutcomePerspective.WHITE, frame.outcomePerspective());
        assertFoolsMateMoves(frame.playedMoves());
        assertEquals(0, frame.candidateSets().size());

        assertEquals(1, frame.samples().size());
        TrainingSample sample = frame.samples().get(0);
        assertEquals(0L, sample.ply());
        assertEquals("rnbqkbnr/pppppppp/8/8/8/5P2/PPPPP1PP/RNBQKBNR b KQkq - 0 1", sample.fen());
        assertTrue(sample.onTrajectory());
        assertEquals(ScoreKind.CP, sample.evalScoreKind());
        assertEquals(35, sample.evalScore());
        assertEquals(SearchBudgetKind.DEPTH, sample.searchBudgetKind());
        assertEquals(6L, sample.searchBudgetValue());

        assertRoundTripsToCanonicalBytes(file, canonical);
    }

