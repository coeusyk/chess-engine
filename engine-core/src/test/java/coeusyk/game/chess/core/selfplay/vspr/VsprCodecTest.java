    private static void assertFoolsMateMoves(List<PlayedMoveDecision> moves) {
        int[] expected = {0x054D, 0x0934, 0x078E, 0x07FB};
        assertEquals(expected.length, moves.size());
        for (int i = 0; i < expected.length; i++) {
            assertEquals(expected[i], moves.get(i).move(), "move index " + i);
            assertEquals(SelectionMechanismKind.BEST_MOVE, moves.get(i).selectionMechanismKind());
            assertTrue(moves.get(i).selectionSeed().isEmpty());
        }
    }

    private static void assertCommonHeader(VsprHeader h) {
        assertEquals(1, h.formatVersion());
        assertArrayEquals(RUN_ID, h.runId());
        assertEquals(1_700_000_000L, h.createdAtEpochSeconds());
        assertEquals("fixture-net-0001", h.generatorNetworkUuid());
        assertArrayEquals(NETWORK_SHA256, h.generatorNetworkSha256());
        assertEquals("fixture-build-0001", h.engineBuildId());
        assertEquals("", h.generatorNetworkPath());
        assertEquals(500, h.maxPlies());
        assertEquals(SearchBudgetKind.DEPTH, h.searchBudgetKind());
        assertEquals(6L, h.searchBudgetValue());
        assertTrue(h.resetSearchStateBetweenGames());
        assertEquals(null, h.adjudicationConfig());
        assertEquals(null, h.diversityConfig());
    }

    private static void assertRoundTripsToCanonicalBytes(VsprFile file, byte[] canonical)
            throws IOException {
        ByteArrayOutputStream out = new ByteArrayOutputStream();
        VsprCodec.write(file, out);
        assertArrayEquals(canonical, out.toByteArray(),
                "encoding the decoded semantic object must reproduce the canonical bytes exactly");
    }

    private static void assertReason(byte[] bytes, VsprFormatException.Reason expected) {
        VsprFormatException ex = assertThrows(VsprFormatException.class,
                () -> VsprCodec.read(new ByteArrayInputStream(bytes)));
        assertEquals(expected, ex.reason());
    }

    private static byte[] base() throws IOException {
        return fixtureBytes("valid_01_ordinary_cp_sample.vspr");
    }

    private static byte[] withByte(byte[] original, int offset, int value) {
        byte[] copy = original.clone();
        copy[offset] = (byte) value;
        return copy;
    }

    /** Recomputes and patches the trailing CRC-32 after an in-body mutation, so the test
     * actually exercises the intended validation branch instead of being masked by an
     * incidental CRC mismatch (frameLength itself is assumed unchanged by the mutation). */
    private static byte[] recomputeCrc(byte[] fixture) {
        byte[] copy = fixture.clone();
        long frameLength = readU32BE(copy, HEADER_LEN);
        int bodyEnd = (int) (FRAME_BODY_START + frameLength);
        CRC32 crc = new CRC32();
        crc.update(copy, FRAME_BODY_START, (int) frameLength);
        writeU32BE(copy, bodyEnd, crc.getValue());
        return copy;
    }

    private static long readU32BE(byte[] b, int offset) {
        return ((long) (b[offset] & 0xFF) << 24) | ((b[offset + 1] & 0xFF) << 16)
                | ((b[offset + 2] & 0xFF) << 8) | (b[offset + 3] & 0xFF);
    }

    private static void writeU32BE(byte[] b, int offset, long value) {
        b[offset] = (byte) (value >>> 24);
        b[offset + 1] = (byte) (value >>> 16);
        b[offset + 2] = (byte) (value >>> 8);
        b[offset + 3] = (byte) value;
    }

    private static byte[] fixtureBytes(String filename) throws IOException {
        return Files.readAllBytes(FIXTURES.resolve(filename));
    }

    private static void assertSha256(byte[] bytes, String expectedHex) {
        try {
            MessageDigest digest = MessageDigest.getInstance("SHA-256");
            byte[] hash = digest.digest(bytes);
            StringBuilder sb = new StringBuilder();
            for (byte b : hash) {
                sb.append(String.format("%02x", b));
            }
            assertEquals(expectedHex, sb.toString(),
                    "fixture bytes on disk no longer match the manifest's committed SHA-256");
        } catch (NoSuchAlgorithmException e) {
            throw new IllegalStateException(e);
        }
    }

    private static byte[] hex(String s) {
        int len = s.length();
        byte[] out = new byte[len / 2];
        for (int i = 0; i < len; i += 2) {
            out[i / 2] = (byte) Integer.parseInt(s.substring(i, i + 2), 16);
        }
        return out;
    }
