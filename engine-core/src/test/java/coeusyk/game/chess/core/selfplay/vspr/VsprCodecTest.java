/**
 * Cross-language contract verification for #211: every fixture under {@code fixtures/vspr/} is
 * the independent oracle -- these bytes were extracted directly from DR-220's own committed hex
 * blocks, not generated by this codec (see {@code fixtures/vspr/MANIFEST.md}). This suite never
 * regenerates an expected hash from {@link VsprCodec}; every expected SHA-256 below is hardcoded
 * from the manifest, independently of whatever the codec under test produces.
 */
